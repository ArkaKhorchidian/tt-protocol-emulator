"""Polyglot host driver for the Tiny Tapeout demo board (MicroPython).

Bit-bangs the chip's host SPI port through the TT SDK's ui_in/uo_out:
ui[0]=SCK, ui[1]=CS_n, ui[2]=MOSI, uo[0]=MISO. Firmware images come from
`python -m polyglot.export` on a PC.

    from polyglot_tt import Polyglot
    import uart_demo                  # generated by polyglot.export
    p = Polyglot.on_demoboard(clock_hz=48_000_000)
    p.load_image(uart_demo.IMAGE)
    p.push(0, b"hello")
"""

ID = 0x504C5947
G_CTRL, G_IRQ, G_FIFOSTAT, G_BANKMAP = 0xC1, 0xC2, 0xC5, 0xC6


class Polyglot:
    def __init__(self, set_ui, get_uo):
        self._set_ui = set_ui        # callable(byte) -> drive ui_in
        self._get_uo = get_uo        # callable() -> uo_out byte
        self.ui_hi = 0               # ui_in[7:3] (free protocol inputs)
        self._ui(0, 1, 0)

    @classmethod
    def on_demoboard(cls, clock_hz=48_000_000):
        from ttboard.demoboard import DemoBoard
        tt = DemoBoard.get()
        tt.shuttle.tt_um_arkakhorchidian_polyglot.enable()
        tt.clock_project_PWM(clock_hz)
        tt.reset_project(True)
        tt.reset_project(False)

        def set_ui(v):
            tt.ui_in.value = v

        def get_uo():
            return int(tt.uo_out.value)
        return cls(set_ui, get_uo)

    # ---- SPI mode 0, MSB first ----
    def _ui(self, sck, cs, mosi):
        self._set_ui((self.ui_hi << 3) | (mosi << 2) | (cs << 1) | sck)

    def xfer(self, data):
        out = bytearray()
        self._ui(0, 0, 0)
        for byte in data:
            rx = 0
            for i in range(7, -1, -1):
                bit = (byte >> i) & 1
                self._ui(0, 0, bit)
                rx = (rx << 1) | (self._get_uo() & 1)
                self._ui(1, 0, bit)
            out.append(rx)
        self._ui(0, 0, 0)
        self._ui(0, 1, 0)
        return out

    def write(self, addr, words):
        if isinstance(words, int):
            words = [words]
        buf = bytearray([0x02, addr & 0xFF])
        for w in words:
            buf += (w & 0xFFFFFFFF).to_bytes(4, "big")
        self.xfer(buf)

    def read(self, addr, n=1):
        rx = self.xfer(bytes([0x03, addr & 0xFF, 0]) + bytes(4 * n))[3:]
        words = [int.from_bytes(rx[4 * i:4 * i + 4], "big") for i in range(n)]
        return words if n > 1 else words[0]

    # ---- convenience ----
    def check_id(self):
        v = self.read(0xC0)
        if v != ID:
            raise RuntimeError("Polyglot not found (ID %08x)" % v)

    def load_image(self, image):
        """image: dict from polyglot.export (imem, cores, bankmap, inject, en)."""
        self.check_id()
        self.write(G_CTRL, 0)
        for base, words in image["imem"]:
            self.write(base, words)
        self.write(G_BANKMAP, image["bankmap"])
        for core, regs, pc in image["cores"]:
            self.write(0x80 + 16 * core, regs)
            self.write(0x80 + 16 * core + 9, pc)
        self.write(G_CTRL, image["en"])
        for core, instr in image["inject"]:
            self.write(0x80 + 16 * core + 15, instr)

    def levels(self, core):
        b = (self.read(G_FIFOSTAT) >> (8 * core)) & 0xFF
        return b & 7, (b >> 3) & 7

    def push(self, core, data):
        for w in data:
            while self.levels(core)[0] >= 4:
                pass
            self.write(0xD0 + core, w)

    def pop_all(self, core):
        _, n = self.levels(core)
        if not n:
            return []
        w = self.read(0xD0 + core, n)
        return w if isinstance(w, list) else [w]
