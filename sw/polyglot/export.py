"""Export firmware + configuration as a MicroPython-loadable image.

    python -m polyglot.export uart > uart_demo.py
"""

import sys

from . import programs as P
from .asm import assemble
from .regs import IO, OUT, IN


def image(placements, bankmap=0xE4, inject=()):
    """placements: list of (core, Program, CoreConfig)."""
    en = 0
    imem, cores = [], []
    for core, prog, cfg in placements:
        imem.append((prog.origin, list(prog.words)))
        cores.append((core, cfg.words(), prog.wrap_target))
        en |= 1 << core
    inj = [(c, assemble(t).words[0]) for c, t in inject]
    return dict(imem=imem, cores=cores, bankmap=bankmap, en=en, inject=inj)


DEMOS = {
    # UART TX on uo[2], RX on ui[3], 8 ticks/bit: baud = clk / (8 * (div+1))
    "uart": lambda: image(
        [(0, P.uart_tx_program(0), P.uart_config(P.uart_tx_program(0), 51, OUT[2])),
         (1, P.uart_rx_program(32), P.uart_config(P.uart_rx_program(32), 51, IN[3], rx=True))],
        inject=[(0, "set pins, 1"), (0, "set pindirs, 1")]),
    # I2C master on uio4 (SDA) / uio5 (SCL), core 0 owns banks 0 and 1
    "i2c": lambda: image(
        [(0, P.i2c_master_program(0), P.i2c_master_config(P.i2c_master_program(0), 30, IO[4], IO[5]))],
        bankmap=0b11_10_00_00),
}


def main():
    name = sys.argv[1] if len(sys.argv) > 1 else "uart"
    print("# generated by polyglot.export (%s)" % name)
    print("IMAGE = %r" % (DEMOS[name](),))


if __name__ == "__main__":
    main()
